/**
 * Core domain representation of a game persisted in Chess Vault.
 *
 * @property id - Unique identifier generated by Chess Vault (MongoDB ObjectId string).
 * @property userId - ID of the user who owns this game record (Clerk User ID).
 * @property userPlayedAs - Color played by the authenticated user in this match (`"white"` | `"black"`).
 * @property folderIds - Array of MongoDB folder ObjectIds this game belongs to, or `null` if unorganized.
 * @property platform - Source platform where the game was played (`"chess.com"` | `"lichess"`).
 * @property platformGameId - Unique game ID assigned by the original platform (e.g. Chess.com UUID or Lichess ID).
 * @property sourceUrl - Direct web link to view the game on the source platform.
 * @property title - Optional match title, formatted as `${whitePlayer.username} vs ${blackPlayer.username}` (or custom title).
 * @property whitePlayer - Details of the White player (`username` and rating).
 * @property blackPlayer - Details of the Black player (`username` and rating).
 * @property result - Outcome of the game (`"white"` | `"black"` | `"draw"`).
 * @property userResult - Outcome from the perspective of the authenticated vault user (`"win"` | `"loss"` | `"draw"`).
 * @property termination - Reason the game ended.
 * @property isRated - Whether the game was played as a rated match (`true`) or unrated (`false`).
 * @property time - Canonical time model containing `timeClass`, live `initial`/`increment`, correspondence `daysPerTurn`, and mainline `clocks`.
 * @property playedAt - Timestamp when the game was completed on the original platform.
 * @property pgn - Full Portable Game Notation string including move sequence and headers.
 * @property finalFen - Optional board state in Forsyth-Edwards Notation (FEN) after the final move.
 * @property notes - Optional user commentary or personal analysis (max 1000 chars).
 * @property tags - Array of user generated game tags (max of 20 tags per game and 50chars each). 
 * @property opening - Optional opening classification containing `eco`, `name`, and `variation`.
 * @property moves - Optional move statistics containing `count` (full moves) and `plies` (half-moves).
 * @property createdAt - Timestamp when the record was persisted in Chess Vault.
 * @property updatedAt - Timestamp when the record was last modified in Chess Vault.
 */
export type Game = z.infer<typeof GameSchema>;

/**
 * Ingestion/normalization-stage game model produced after fetching and standardizing external platform data.
 *
 * Represents games before persistence in Chess Vault. Structurally identical to `Game`,
 * but omits database persistence metadata (`id`, `createdAt`, `updatedAt`).
 *
 * Data Lifecycle Flow:
 * `External Platform Data → normalize → NormalizedGame → persist → Game`
 */
export type NormalizedGame = Omit<Game, "id" | "createdAt" | "updatedAt">;
